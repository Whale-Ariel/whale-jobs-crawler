def annotate_code(source):
    """给手工选定的关键行加注释；不生成无意义的逐行中文翻译。"""
    output = []
    for line in source.splitlines():
        explanation = COMMENTS.get(line.strip())
        if explanation:
            indent = line[:len(line)-len(line.lstrip())]
            output.append(indent + '# ' + explanation)
        output.append(line)
    return '\n'.join(output)
